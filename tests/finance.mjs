import assert from "node:assert/strict";
import { recurringForMonth, monthlyPlan, goalMonthlyContribution } from "../finance.js";

const rent = { id: "rent", type: "expense", title: "Aluguel", amount: 1800.10, recurring: true, paid: true, date: "2024-01-31", paidDate: "2024-01-31" };
const february = recurringForMonth([rent], "2024-02");
assert.equal(february[0].date, "2024-02-29", "dia 31 deve respeitar fevereiro bissexto");
assert.equal(february[0].paid, false, "pagar janeiro não paga fevereiro");
assert.equal(recurringForMonth([rent], "2025-02")[0].date, "2025-02-28");
assert.equal(recurringForMonth([rent], "2024-03")[0].date, "2024-03-31", "o dia original deve ser recuperado após fevereiro");
assert.deepEqual(recurringForMonth([rent], "2023-12"), [], "não gerar parcelas anteriores ao cadastro");
assert.equal(recurringForMonth([rent], "2024-02")[0].id, february[0].id, "IDs devem ser iguais em dispositivos diferentes");
assert.equal(rent.paidDate, "2024-01-31", "a projeção não pode alterar o histórico");
const paidFebruary = { ...february[0], virtual: undefined, paid: true, paidDate: "2024-02-20" };
assert.equal(recurringForMonth([rent, paidFebruary], "2024-02").length, 1, "não duplicar a parcela materializada");
assert.equal(recurringForMonth([rent, paidFebruary], "2024-02")[0].paid, true);
assert.deepEqual(recurringForMonth([rent], "2024-02", [{ collection: "transactions", id: february[0].id, deletedAt: 1 }]), [], "uma parcela excluída não deve reaparecer");
assert.deepEqual(recurringForMonth([{ ...rent, recurrenceEnd: "2024-02" }], "2024-03"), [], "respeitar encerramento da série");
assert.equal(recurringForMonth([paidFebruary], "2024-02").length, 1, "manter pagamentos após excluir a série");
const salary = { id: "salary", type: "income", amount: 5000.25, date: "2024-02-01" };
const plan = monthlyPlan([rent, salary], "2024-02");
assert.equal(plan.pending, 1800.10);
assert.equal(plan.expenses, 0, "conta pendente não é despesa paga");
assert.equal(plan.projected, 3200.15, "cálculos em centavos não devem acumular arredondamentos");
const paidPlan = monthlyPlan([rent, salary, paidFebruary], "2024-02");
assert.equal(paidPlan.projected, plan.projected, "pagar uma conta mantém a projeção, sem descontá-la duas vezes");
assert.equal(paidPlan.pending, 0);
assert.equal(monthlyPlan([rent, salary], "2024-03").income, 0, "não projetar uma renda não cadastrada");
assert.equal(goalMonthlyContribution({ target: 12000, saved: 3000, deadline: "2026-12-31" }, new Date(2026, 9, 15)), 3000);
assert.equal(goalMonthlyContribution({ target: 100, saved: 0, deadline: "2026-12-31" }, new Date(2026, 9, 15)), 33.34);
assert.equal(goalMonthlyContribution({ target: 100, saved: 100, deadline: "2026-12-31" }, new Date(2026, 9, 15)), 0);
assert.equal(goalMonthlyContribution({ target: 100, saved: 0 }, new Date()), null);
process.stdout.write("✓ Planejamento: recorrência mensal, anos bissextos, exclusões, projeção e metas validados\n");
